# Comparison Operators in Python
# Comparison operators are used to compare two values. They return a boolean value (True or False) based on the comparison.

a = 10
b = 20
print("a is equal to b:", a == b)  # checks if a is equal to b, returns False
print("a is not equal to b:", a != b)  # checks if a is not equal to b, returns True
print("a is greater than b:", a > b)  # checks if a is greater than b, returns False
print("a is less than b:", a < b)  # checks if a is less than b, returns True
print("a is greater than or equal to b:", a >= b)  # checks if a is greater than or equal to b, returns False
print("a is less than or equal to b:", a <= b)  # checks if a is less than or equal to b, returns True

age = 18
print("age is equal to 65:", age == 65)  # checks if age is equal to 65, returns False
print("age is not equal to 65:", age != 65)  # checks if age is not equal to 65, returns True
print("age is greater than 65:", age > 65)  # checks if age is greater than 65, returns False
print("age is less than 65:", age < 65)  # checks if age is less than 65, returns True
print("age is greater than or equal to 65:", age >= 65)  # checks if age is greater than or equal to 65, returns False
print("age is less than or equal to 65:", age <= 65)  # checks if age is less than or equal to 65, returns True