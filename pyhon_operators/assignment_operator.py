# Assignment Operators in Python
# Assignment operators are used to assign values to variables.   

x = 5  # assigns the value 5 to the variable x
print(x)  # prints the value of x

x+= 3  # adds 3 to the current value of x and assigns the result back to x
print(x)  # prints the updated value of x

x-= 2  # equivalent to x = x - 2, subtracts 2 from the current value of x and assigns the result back to x
print(x)  # prints the updated value of x

x*= 4  # equivalent to x = x * 4, multiplies the current value of x by 4 and assigns the result back to x
print(x)  # prints the updated value of x

x/= 2  # equivalent to x = x / 2, divides the current value of x by 2 and assigns the result back to x
print(x)  # prints the updated value of x

x%= 3  # equivalent to x = x % 3, calculates the modulus of the current value of x by 3 and assigns the result back to x
print(x)  # prints the updated value of x

x**= 2  # equivalent to x = x ** 2, raises the current value of x to the power of 2 and assigns the result back to x
print(x)  # prints the updated value of x

x//= 3  # equivalent to x = x // 3, performs floor division of the current value of x by 3 and assigns the result back to x
print(x)  # prints the updated value of x

x= 5  # reassigns the value 5 to the variable x
print(x)  # prints the reassigned value of x

x&= 3  # equivalent to x = x & 3, performs a bitwise AND operation between the current value of x and 3 and assigns the result back to x
print(x)  # prints the updated value of x   

x|= 2  # equivalent to x = x | 2, performs a bitwise OR operation between the current value of x and 2 and assigns the result back to x
print(x)  # prints the updated value of x   

x^= 1  # equivalent to x = x ^ 1, performs a bitwise XOR operation between the current value of x and 1 and assigns the result back to x
print(x)  # prints the updated value of x

x<<= 1  # equivalent to x = x << 1, performs a left shift operation on the current value of x by 1 and assigns the result back to x
print(x)  # prints the updated value of x

x>>= 1  # equivalent to x = x >> 1, performs a right shift operation on the current value of x by 1 and assigns the result back to x
print(x)  # prints the updated value of x

x= 5  # reassigns the value 5 to the variable x
print(x)  # prints the reassigned value of x
