# Arithmetic operators
a = 10
b = 23
print("addition of two number a & b is :",a + b)   # addition of two number a & b is : 33

print("subtraction of two number a & b is :",a - b) # subtraction of two number a & b is : -13

print("division of two number a & b is :",a / b)  # division of two number a & b is : 0.43478260869565216

print("multiplication of two number a & b is :",a * b)  # multiplication of two number a & b is : 230

print("modulus of two number a & b is :",a % b)  # modulus operator gives remainder of the division

print("floor division of two number a & b is :",a // b)  # floor division operator gives quotient of the division

print("exponentiation of two number a & b is :",a ** b)   
