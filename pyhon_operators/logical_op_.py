# Logical operators in python:
# Logical operators are used to combine conditional statements. In python, we have the following logical operators:
# and: returns True if both statements are true
# or: returns True if one of the statements is true
# not: returns True if the statement is false

a = 10
b = 20
print("a is greater than 5 and b is less than 25:", a > 5 and b < 25)  # returns True
print("a is greater than 5 or b is less than 15:", a > 5 or b < 15)  # returns True
print("not(a is greater than 5 and b is less than 25):", not(a > 5 and b < 25))  # returns False 